"""Build docs/results.md from the committed results.csv files (no hand-typed numbers).

  python scripts/make_results_table.py
"""

import sys
from pathlib import Path

import pandas as pd

root = Path(__file__).parents[1]
RUNS = [("mars_resnet50_frozen", "ResNet-50 (ImageNet, frozen)"),
        ("mars_osnet_frozen", "OSNet (ImageNet, frozen)"),
        ("mars_osnet_finetuned", "OSNet (fine-tuned on MARS train)")]
COLS = ["method", "rank1", "rank5", "mAP", "dbscan_f1", "agglomerative_f1", "agglomerative_clusters_per_identity"]
NAMES = ["Pooling", "Rank-1", "Rank-5", "mAP", "DBSCAN F1", "Agglo. F1", "Clusters / identity"]

lines = ["# Results (generated by scripts/make_results_table.py)", "",
         "MARS-style protocol, not the official MARS lists: 100-identity test subset (seed 255, 50 test identities "
         "plus distractors), camera-1 tracklet queries (n=145), single seed. Clustering is scored at frame level with "
         "thresholds tuned on a held-out identity half. Numbers are not comparable to published MARS scores.", ""]
for folder, title in RUNS:
    path = root / "results" / folder / "results.csv"
    if not path.exists():
        print("missing", path, file=sys.stderr)
        continue
    df = pd.read_csv(path)[COLS].round(3)
    df.columns = NAMES
    lines += [f"## {title}", "", df.to_markdown(index=False), ""]
(root / "docs" / "results.md").write_text("\n".join(lines))
print("wrote docs/results.md")
